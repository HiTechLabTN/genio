def resolve_lang(explicit=None):
    if explicit in LANGS:
        return explicit
    env = (os.environ.get("GENIO_LANG") or "").strip().lower()
    if env in LANGS:
        return env
    loc = (os.environ.get("LANG") or os.environ.get("LC_ALL") or "").lower()
    if loc.startswith("fr"):
        return "fr"
    if loc.startswith("en"):
        return "en"
    return "tu"


def t(key, lang="tu", **vars):
    table = STRINGS.get(lang, STRINGS["tu"])
    s = table.get(key, STRINGS["tu"].get(key, key))
    for k, v in vars.items():
        s = s.replace("{" + k + "}", str(v))
    return s


def wordlist(lang, key):
    return [w for w in t(key, lang).split("|") if w]
